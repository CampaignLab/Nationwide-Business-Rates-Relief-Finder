export function validateIndex(value) {
  if(value?.cohort?.id!=='rhl_new_full_relief' || !Number.isSafeInteger(value.cohort.lower_rv_exclusive) || !Number.isSafeInteger(value.cohort.upper_rv_inclusive) || value.cohort.lower_rv_exclusive<0 || value.cohort.upper_rv_inclusive<=value.cohort.lower_rv_exclusive) throw new Error('This dataset does not identify the new-full-relief RHL cohort. Rerun stages 6 and 7 with the updated pipeline.');
  if (!value || !Array.isArray(value.constituencies) || value.constituencies.length > 1000) throw new Error('Choose a valid constituency_index.json generated by the pipeline.');
  const seen = new Set();
  for (const row of value.constituencies) {
    if (!row || typeof row.code !== 'string' || !/^E14\d{6}$/.test(row.code) || seen.has(row.code) || typeof row.name !== 'string' || typeof row.region !== 'string' || !row.counts) throw new Error('The index has an invalid or duplicate constituency.');
    seen.add(row.code);
    for (const key of ['properties_in_list','target_new_full_relief','now_possibly_eligible_now','now_not_flagged']) {
      if (!Number.isSafeInteger(row.counts[key]) || row.counts[key] < 0) throw new Error('The index has invalid property counts.');
    }
    if (row.counts.target_new_full_relief > row.counts.properties_in_list) throw new Error('Flagged counts exceed total properties.');
    if(value.screening_version===1){
      for(const key of ['likely_candidate','needs_review'])if(!Number.isSafeInteger(row.counts[key])||row.counts[key]<0)throw new Error('Invalid screening counts.');
      if(row.counts.likely_candidate+row.counts.needs_review!==row.counts.target_new_full_relief)throw new Error('Screening counts do not reconcile.');
    }
    for (const [format, path] of Object.entries(row.files || {})) {
      if (!['csv','xlsx'].includes(format) || typeof path !== 'string' || !path.startsWith(`constituencies/${format}/`) || path.includes('..') || path.includes('\\') || !path.endsWith(`.${format}`)) throw new Error('The index contains an invalid download path.');
    }
  }
  return value;
}

export function filterRows(rows, query, region) {
  const q = query.trim().toLocaleLowerCase('en-GB');
  return rows.filter(r => (!region || r.region === region) && `${r.name} ${r.code}`.toLocaleLowerCase('en-GB').includes(q)).sort((a,b)=>a.name.localeCompare(b.name,'en-GB'));
}
